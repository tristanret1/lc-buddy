DOCS_DIR = ROOT / "docs"
ICON = {"todo": "⬜", "in_progress": "🔧", "solved": "✅", "review_due": "🔁", "mastered": "🏆"}
INLINE_LIMIT = 150  # lists up to this size get their full tables inside README


def bar(frac: float, width: int = 24) -> str:
    n = round(max(0.0, min(1.0, frac)) * width)
    return "█" * n + "░" * (width - n)


def verdict(score: int) -> str:
    if score >= 85:
        return "Interview-ready. Keep reviews warm and do timed mocks."
    if score >= 65:
        return "Close. Finish the hard tier and clear overdue reviews."
    if score >= 40:
        return "Mid-way. Mediums are the priority now."
    if score >= 15:
        return "Foundations forming. Stay on the daily cadence."
    return "Just started. One problem a day beats a weekend binge."


def _lc_url(p: dict) -> str:
    if p.get("slug"):
        return f"https://leetcode.com/problems/{p['slug']}/"
    return "https://leetcode.cn/problemset/"


def _title_cell(p: dict) -> str:
    title = p.get("title") or p.get("title_en") or p.get("slug") or p["id"]
    d = solution_dir(p["slug"]) if p.get("slug") else None
    link = f"solutions/{d.name}/" if d else _lc_url(p)
    return f"[{title}]({link})"


def _row(p: dict, data: dict, cfg: dict, rel: str = "") -> str:
    st = status_of(data, p.get("slug"))
    e = data["problems"].get(p.get("slug") or "", {})
    flags = []
    if p.get("premium"):
        flags.append("会员")
    if p.get("cn_only"):
        flags.append("cn")
    if not in_target(p, cfg, ignore_focus=True) and not flags:
        flags.append("＞rating")
    rating = str(p["rating"]) + ("≈" if p.get("rating_approx") else "") if p.get("rating") else ""
    nr = e.get("srs", {}).get("next_review") or ("🏆" if st == "mastered" else "")
    note = (p.get("note") or "").replace("|", "\\|")
    title = _title_cell(p)
    if rel and title.startswith("[") and "](solutions/" in title:
        title = title.replace("](solutions/", f"]({rel}solutions/")
    en = p.get("title_en") or ""
    return (f"| {ICON[st]} | {p['id']} | {title} | {en} | {p.get('difficulty') or ''} | {rating} | "
            f"{' '.join(flags)} | {note} | {e.get('attempts') or ''} | {e.get('solved_at') or ''} | {nr} |")


TABLE_HEAD = ("| | # | 题目 | Title | Difficulty | Rating | Flags | Note | Attempts | Solved | Next review |\n"
              "|---|---|---|---|---|---|---|---|---|---|---|")


def render_list_doc(L: dict, data: dict, cfg: dict, ids: dict) -> str:
    out = [f"# {L['name']}\n", f"Source: {L['url']}  ·  {L['count']} entries  ·  generated {date.today().isoformat()}\n",
           "Legend: ⬜ todo · 🔧 in progress · ✅ solved · 🔁 review due · 🏆 mastered · "
           "Flags: 会员 = premium, cn = leetcode.cn only, ＞rating = above your max_rating\n"]
    for sec in L["sections"]:
        ps = [ids[i] for i in sec["ids"] if i in ids]
        done = sum(1 for p in ps if status_of(data, p.get("slug")) in ("solved", "mastered", "review_due"))
        tgt = sum(1 for p in ps if in_target(p, cfg, ignore_focus=True))
        out.append(f"## {sec['path']}\n")
        out.append(f"{done} solved / {tgt} in target / {len(ps)} listed\n")
        out.append(TABLE_HEAD)
        for p in ps:
            out.append(_row(p, data, cfg, rel="../"))
        out.append("")
    return "\n".join(out)


def render() -> str:
    cfg = load_config()
    data = load()
    plist = load_list()
    ids = by_id()
    s = stats(data)
    inline = s["total_all"] <= INLINE_LIMIT
    L = []
    L.append(f"# LC Buddy — {plist['name']}\n")
    L.append(f"_Auto-generated by `python3 -m lcb readme` on {date.today().isoformat()}. Do not edit by hand._\n")
    if plist.get("description"):
        L.append(plist["description"] + "\n")

    L.append("## Interview readiness\n")
    L.append(f"**{s['readiness']} / 100**  `{bar(s['readiness'] / 100)}`  — {verdict(s['readiness'])}\n")
    parts = s["readiness_parts"]
    L.append("| Component | Weight | Score |\n|---|---|---|")
    L.append(f"| Coverage (solved / goal {s['goal']}) | 40% | {parts['coverage']:.0%} |")
    L.append(f"| Difficulty (medium + hard ≥ 70% of goal) | 20% | {parts['difficulty']:.0%} |")
    L.append(f"| Topic breadth (each list vs its share of the goal) | 20% | {parts['topics']:.0%} |")
    L.append(f"| Retention (reviews on schedule) | 20% | {parts['retention']:.0%} |\n")
    filt = [f"rating ≤ {s['max_rating']}" if s["max_rating"] else "any rating",
            "no premium" if s["skip_premium"] else "premium included", "no cn-only"]
    if s["focus"]:
        filt.append("focus: " + ", ".join(s["focus"]))
    L.append(f"Target set: **{s['total']}** of {s['total_all']} listed problems ({'; '.join(filt)}). "
             f"Goal: **{s['goal']}** solved.\n")

    L.append("## Progress\n")
    L.append(f"`{bar(s['solved'] / s['goal'] if s['goal'] else 0)}` **{s['solved']} / {s['goal']}** toward goal"
             f" · {s['solved_all']} solved in total · 🏆 {s['mastered']} mastered · 🔧 {s['in_progress']} in progress"
             f" · 🔁 {s['review_due']} reviews due · 🔥 {s['streak']}-day streak\n")
    L.append("| Difficulty | Solved | In target | |\n|---|---|---|---|")
    for d in ("Easy", "Medium", "Hard"):
        v = s["by_difficulty"].get(d, {"solved": 0, "total": 0})
        L.append(f"| {d} | {v['solved']} | {v['total']} | `{bar(v['solved'] / v['total'] if v['total'] else 0, 12)}` |")
    L.append("")

    L.append("## Pace & ETA\n")
    L.append(f"- Last 14 days: **{s['recent_14d']}** new problems solved ({s['actual_pace']:.2f}/day). Plan assumes {s['planned_pace']:.0f}/day.")
    L.append(f"- Remaining to goal: **{s['remaining']}** problems.")
    if s["remaining"]:
        L.append(f"- ETA at planned pace: **{s['eta_planned']}**" +
                 (f" · at actual pace: **{s['eta_actual']}**" if s["eta_actual"] else " · at actual pace: n/a (fewer than 3 solves in 14 days)"))
    else:
        L.append("- Goal reached. Raise `goal` in config.json, rotate reviews, and start timed mocks.")
    if s.get("target_date"):
        days_left = (date.fromisoformat(s["target_date"]) - date.today()).days
        need = s["remaining"] / max(days_left, 1)
        L.append(f"- Target date **{s['target_date']}** is {days_left} days away → need **{need:.1f}/day** to reach the goal.")
    L.append("")

    L.append("## Today's plan\n")
    pl = plan(data)
    rot = pl["rotation"]
    if rot and rot.get("current"):
        L.append(f"**Category: {rot['current_name']}** — block {rot['in_block']}/{rot['block']} of cycle {rot['cycle']}"
                 + (f", then → {rot['next_name']}" if rot.get("next") else "") + "\n")
    L.append("| Priority | Problem | Why |\n|---|---|---|")
    for p in pl["new"]:
        L.append(f"| 1 · 新题 | {p['id']}. {_title_cell(p)} ({p.get('difficulty')}{', ' + str(p['rating']) if p.get('rating') else ''}) | {p['topic']} / {p['section']} |")
    for p in pl["unfinished"]:
        L.append(f"| 1 · 未通关 | {p['id']}. {_title_cell(p)} | {p['attempts']} failed attempt(s), finish it |")
    for p in pl["weak"]:
        L.append(f"| 2 · 错题 | {p['id']}. {_title_cell(p)} | stumbled before; due {p['next_review']} (box {p['box']}) |")
    for p in pl["old"]:
        L.append(f"| 3 · 旧题 | {p['id']}. {_title_cell(p)} | forgetting curve; due {p['next_review']} (box {p['box']}) |")
    if pl["deferred"]:
        L.append(f"| — | +{pl['deferred']} more reviews due | capped by `daily_reviews` |")
    L.append("")
    if rot:
        L.append("<details><summary>Rotation state</summary>\n")
        L.append("| | List | Solved | In target | Block | Cycles done |\n|---|---|---|---|---|---|")
        for r in rot["lists"]:
            L.append(f"| {'▶' if r.get('current') else ''} | {r['name']} | {r['solved']} | {r['target']} | "
                     f"{r['in_block']}/{rot['block']} | {r['level']} |")
        L.append("\n</details>\n")

    L.append("## Job pipeline\n")
    js = jobs.summary()
    if not js["total"]:
        L.append("_Empty. `/job-search` to find roles, `/job-add <url>` to track one._\n")
    else:
        L.append("  ·  ".join(f"**{n}** {st}" for st, n in js["counts"].items() if n) + "\n")
        rows = sorted(js["active"] + js["found"], key=lambda j: (j.get("next_date") or "9999", -(j.get("fit") or 0)))
        if rows:
            L.append("| Company | Role | Status | Fit | Next | When |\n|---|---|---|---|---|---|")
            today = date.today().isoformat()
            for j in rows[:15]:
                when = j.get("next_date") or ""
                if when and when < today:
                    when += " ‼️"
                elif when == today:
                    when += " ⏰"
                title = f"[{j['title']}]({j['url']})" if j.get("url") else j["title"]
                L.append(f"| {j['company']} | {title} | {j['status']} | {j.get('fit') if j.get('fit') is not None else '-'} | {j.get('next_action', '')} | {when} |")
            if len(rows) > 15:
                L.append(f"\n_+{len(rows) - 15} more — `python3 -m lcb jobs`_")
        L.append("")

    L.append("## System design\n")
    sd = design.summary()
    L.append(f"Fundamentals `{bar(sd['fund_done'] / sd['fund_total'], 12)}` {sd['fund_done']}/{sd['fund_total']}  ·  "
             f"Designs `{bar(sd['design_done'] / sd['design_total'], 12)}` {sd['design_done']}/{sd['design_total']}  ·  "
             f"Resume deep dives `{bar(sd['proj_done'] / sd['proj_total'], 12)}` {sd['proj_done']}/{sd['proj_total']}\n")
    if sd["review"]:
        L.append("- 🔁 re-visit due: " + ", ".join(f"`{x}`" for x in sd["review"]))
    if sd["in_progress"]:
        L.append("- 🔧 in progress: " + ", ".join(f"`{x}`" for x in sd["in_progress"]))
    if sd["next"]:
        L.append(f"- ⬜ next: `{sd['next']['slug']}` {sd['next']['title']} ({sd['next']['zh']}) — `/sd-daily`")
    if sd.get("next_project"):
        L.append(f"- 🗣 next resume deep dive: `{sd['next_project']['slug']}` {sd['next_project']['title']} — `/sd-daily {sd['next_project']['slug']}`")
    L.append("- Notes land in `design/notes/<slug>.md`; `python3 -m lcb sd list` for the whole curriculum.\n")

    L.append("## By list\n")
    L.append("| List | Solved | In target | Listed | |\n|---|---|---|---|---|")
    for key, v in s["by_list"].items():
        doc = f"docs/{key}.md"
        L.append(f"| [{v['name']}]({doc}) | {v['solved']} | {v['target']} | {v['total']} | "
                 f"`{bar(v['solved'] / v['target'] if v['target'] else 0, 12)}` |")
    L.append("")

    L.append("## Sections\n")
    L.append("Legend: ⬜ todo · 🔧 in progress · ✅ solved · 🔁 review due · 🏆 mastered\n")
    for Lst in plist["lists"]:
        v = s["by_list"].get(Lst["key"], {"solved": 0, "target": 0})
        L.append(f"<details><summary><b>{Lst['name']}</b> — {v['solved']}/{v['target']} · "
                 f"<a href=\"docs/{Lst['key']}.md\">full table</a></summary>\n")
        if inline:
            for sec in Lst["sections"]:
                ps = [ids[i] for i in sec["ids"] if i in ids]
                L.append(f"\n**{sec['path']}**\n")
                L.append(TABLE_HEAD)
                for p in ps:
                    L.append(_row(p, data, cfg))
        else:
            L.append("| Section | Solved | In target | Listed | |\n|---|---|---|---|---|")
            for sec in Lst["sections"]:
                sv = v.get("sections", {}).get(sec["path"], {"solved": 0, "target": 0, "total": 0})
                L.append(f"| {sec['path']} | {sv['solved']} | {sv['target']} | {sv['total']} | "
                         f"`{bar(sv['solved'] / sv['target'] if sv['target'] else 0, 10)}` |")
        L.append("\n</details>\n")

    L.append("## Recent activity\n")
    acts = recent_activity(data, 12)
    if not acts:
        L.append("_Nothing yet. Run `/lc-daily` to get your first problem._")
    for a in acts:
        extra = {k: v for k, v in a.items() if k not in ("at", "event", "slug")}
        L.append(f"- `{a['at'][:16]}` **{a['event']}** {a['slug']}" + (f" `{extra}`" if extra else ""))
    L.append("")

    L.append("## How this repo works\n")
    L.append("- `/lc-daily` — scaffold today's problem into `solutions/NNNN-slug/` (statement, stub, example tests).")
    L.append("- `/lc-test [slug]` — run `tests.json` locally; `--remote` runs LeetCode's judge on the same cases.")
    L.append("- `/lc-submit [slug]` — submit to LeetCode, record the verdict in `progress.json`, regenerate this README, commit.")
    L.append("- `/lc-status` — readiness, due reviews, what to do next. `/lc-review` — spaced-repetition re-solve.")
    L.append("- Target set = list minus premium / cn-only / above `max_rating`; `focus` narrows it to lists or sections. "
             "Edit `config.json` (`python3 -m lcb config --set max_rating=2000 --set 'focus=[\"dp\"]'`).")
    rot_cfg = cfg.get("rotation") or {}
    L.append(f"- Scheduler: rotate through the lists, {rot_cfg.get('block', 5)} new problems per list per cycle, then move on; "
             "the cycle repeats until every list's target set is done. Each day: 新题 (current list) → 错题 → 旧题.")
    L.append("- Forgetting curve: an accepted problem comes back for review after "
             + " → ".join(f"{d}d" for d in cfg["review_intervals"]) + "; a clean re-solve climbs the ladder. "
             f"错题 (accepted only after a wrong submission, a stumbled review, or confidence ≤ 2) come back after {cfg.get('weak_interval', 1)}d "
             f"and are queued before ordinary reviews. At most {cfg.get('daily_reviews', 2)} reviews per day.")
    L.append("- `/job-search` — web-search roles matching `jobs/profile.json`; `/job-add <url>` — fetch a JD, score fit, track it; "
             "`/job-status` — the pipeline and what's due. State: `jobs/pipeline.json`, JDs in `jobs/jd/`.")
    L.append("- `/sd-daily` — one system-design session (fundamental: teach + check questions; design: 45-min mock scored by rubric). "
             "`python3 -m lcb sd list` shows the curriculum; notes in `design/notes/`.")
    L.append("- The AI coach never writes the solution for you unless you explicitly ask — see `CLAUDE.md`.")
    L.append("")
    return "\n".join(L)


def write() -> str:
    cfg = load_config()
    data = load()
    plist = load_list()
    ids = by_id()
    DOCS_DIR.mkdir(exist_ok=True)
    for Lst in plist["lists"]:
        (DOCS_DIR / f"{Lst['key']}.md").write_text(render_list_doc(Lst, data, cfg, ids), encoding="utf-8")
    text = render()
    README_FILE.write_text(text, encoding="utf-8")
    return text
